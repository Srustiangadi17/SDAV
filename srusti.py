import numpy as np

# Sample space for 3 coin tosses
sample_space = np.array([
    "HHH", "HHT", "HTH", "HTT",
    "THH", "THT", "TTH", "TTT"
])

print("Sample Space:")
print(sample_space)

# Total outcomes
total = len(sample_space)

# a) Exactly 3 Heads
exactly_3 = np.array([x.count("H") == 3 for x in sample_space])
p3 = np.sum(exactly_3) / total

# b) Exactly 2 Heads
exactly_2 = np.array([x.count("H") == 2 for x in sample_space])
p2 = np.sum(exactly_2) / total

# c) At least 1 Head
at_least_1 = np.array([x.count("H") >= 1 for x in sample_space])
p1 = np.sum(at_least_1) / total

print("Probability of exactly 3 Heads:", p3)
print("Probability of exactly 2 Heads:", p2)
print("Probability of at least 1 Head:", p1)

import numpy as np

# Sample space of a die
die = np.array([1, 2, 3, 4, 5, 6])

total = len(die)

# a) Even number
even = np.sum(die % 2 == 0)
print("Probability of even number:", even / total)

# b) Odd number
odd = np.sum(die % 2 != 0)
print("Probability of odd number:", odd / total)

# c) Number greater than 4
greater_4 = np.sum(die > 4)
print("Probability of number greater than 4:", greater_4 / total)

# d) Number less than or equal to 3
less_equal_3 = np.sum(die <= 3)
print("Probability of number <= 3:", less_equal_3 / total)

import numpy as np

# Sample space of two dice
dice1 = np.array([1, 2, 3, 4, 5, 6])
dice2 = np.array([1, 2, 3, 4, 5, 6])

sample_space = np.array(np.meshgrid(dice1, dice2)).T.reshape(-1, 2)

print("Sample Space:")
print(sample_space)

total = len(sample_space)

# a) Sum is 7
a = np.sum(sample_space[:, 0] + sample_space[:, 1] == 7)
print("a) Probability of sum 7:", a / total)

# b) Sum is greater than 8
b = np.sum(sample_space[:, 0] + sample_space[:, 1] > 8)
print("b) Probability of sum greater than 8:", b / total)

# c) Both dice show same number
c = np.sum(sample_space[:, 0] == sample_space[:, 1])
print("c) Probability of same number:", c / total)

# d) At least one die shows 6
d = np.sum((sample_space[:, 0] == 6) | (sample_space[:, 1] == 6))
print("d) Probability of at least one 6:", d / total)

